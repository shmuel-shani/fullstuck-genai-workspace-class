const matrix1 = []; // המטריצה הראשית
let counter = 0;    // המונה שלנו שיתקדם מ-0 עד 99

// רצים על 10 שורות (i)
for (let i = 0; i < 10; i++) {
    const row = []; // בונים שורה חדשה וריקה
    
    // רצים על 10 תאים בתוך השורה (j)
    for (let j = 0; j < 10; j++) {
        row.push(counter); // מכניסים את המספר לשורה
        counter++;         // מקדמים את המונה ב-1 לקראת התא הבא
    }
    
    // סיימנו למלא את השורה ב-10 מספרים, עכשיו מכניסים אותה למטריצה
    matrix1.push(row);
}

console.log(matrix1);

